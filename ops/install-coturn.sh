#!/usr/bin/env bash
# Install + configure coturn (STUN/TURN relay) for 密聊 voice/video calls, and point the app at it.
#
#   sudo bash ops/install-coturn.sh [domain]
#
# - TURN credentials are short-lived HMAC tokens handed out by the app (use-auth-secret); no static passwords.
# - Relaying to private / loopback / cloud-metadata addresses is forbidden, so the relay can't be used to reach the
#   server's internal network.
# - Media stays end-to-end encrypted (DTLS-SRTP); the relay only forwards encrypted packets.
#
# Afterwards open these ports in the Alibaba Cloud security group AND the BaoTa firewall:
#   3478/udp, 3478/tcp, 5349/tcp, 49160-49200/udp
set -euo pipefail
. "$(dirname "$0")/common.sh"
[ "$(id -u)" = 0 ] || { echo "请用 root 运行"; exit 1; }

DOMAIN=${1:-$(as_app cat "$APP_DIR/.env" 2>/dev/null | grep -E '^PUBLIC_ORIGIN=' | sed -E 's#^PUBLIC_ORIGIN=https?://##; s#/.*$##')}
[ -n "$DOMAIN" ] || { echo "用法: $0 <域名>，例如 $0 chat.example.com"; exit 1; }
MIN_PORT=${TURN_MIN_PORT:-49160}
MAX_PORT=${TURN_MAX_PORT:-49200}

# ---------------------------------------------------------------- 1) install
if ! command -v turnserver >/dev/null 2>&1; then
  log "安装 coturn…"
  if command -v apt-get >/dev/null 2>&1; then
    DEBIAN_FRONTEND=noninteractive apt-get update -y >/dev/null
    DEBIAN_FRONTEND=noninteractive apt-get install -y coturn >/dev/null
  elif command -v dnf >/dev/null 2>&1; then
    dnf install -y epel-release >/dev/null 2>&1 || true
    dnf install -y coturn >/dev/null
  elif command -v yum >/dev/null 2>&1; then
    yum install -y epel-release >/dev/null 2>&1 || true
    yum install -y coturn >/dev/null
  else
    echo "不认识的系统包管理器，请手动安装 coturn"; exit 1
  fi
fi
command -v turnserver >/dev/null || { echo "coturn 安装失败"; exit 1; }

# ---------------------------------------------------------------- 2) addresses (ECS: private IP with 1:1 NAT to the public IP)
PRIVATE_IP=$(ip -4 route get 1.1.1.1 2>/dev/null | awk '{for(i=1;i<=NF;i++) if($i=="src"){print $(i+1); exit}}')
PUBLIC_IP=${PUBLIC_IP:-$(curl -fsS --max-time 5 http://100.100.100.200/latest/meta-data/eipv4 2>/dev/null || curl -fsS --max-time 5 https://api.ipify.org 2>/dev/null || true)}
[ -n "$PRIVATE_IP" ] || { echo "无法确定本机内网 IP"; exit 1; }
[ -n "$PUBLIC_IP" ] || { echo "无法确定公网 IP，请用 PUBLIC_IP=x.x.x.x $0 重新运行"; exit 1; }
EXTERNAL="$PUBLIC_IP"
[ "$PUBLIC_IP" != "$PRIVATE_IP" ] && EXTERNAL="$PUBLIC_IP/$PRIVATE_IP"

# ---------------------------------------------------------------- 3) TLS cert (the one BaoTa issued for the site)
CERT=""; KEY=""
for d in "/www/server/panel/vhost/cert/$DOMAIN" "/etc/letsencrypt/live/$DOMAIN"; do
  if [ -f "$d/fullchain.pem" ] && { [ -f "$d/privkey.pem" ] || [ -f "$d/privkey.key" ]; }; then
    CERT="$d/fullchain.pem"; KEY="$d/privkey.pem"; [ -f "$KEY" ] || KEY="$d/privkey.key"; break
  fi
done
TURN_USER=$(id -un turnserver 2>/dev/null || id -un coturn 2>/dev/null || echo root)
TLS_DIR=/etc/coturn-tls
if [ -n "$CERT" ]; then
  # coturn runs unprivileged and can't read BaoTa's cert dir: keep a private copy (refreshed by the timer below)
  install -d -m 750 -o root -g "$(id -gn "$TURN_USER")" "$TLS_DIR"
  install -m 640 -o root -g "$(id -gn "$TURN_USER")" "$CERT" "$TLS_DIR/fullchain.pem"
  install -m 640 -o root -g "$(id -gn "$TURN_USER")" "$KEY" "$TLS_DIR/privkey.pem"
else
  log "⚠ 没找到 $DOMAIN 的证书，只启用 3478（不启用 TLS 5349）"
fi

# ---------------------------------------------------------------- 4) shared secret (reuse if already configured)
SECRET=$(as_app cat "$APP_DIR/.env" 2>/dev/null | grep -E '^TURN_SECRET=' | cut -d= -f2- || true)
[ -n "$SECRET" ] || SECRET=$(head -c 32 /dev/urandom | base64 | tr -d '=+/' | cut -c1-40)

CONF=/etc/turnserver.conf
[ -f "$CONF" ] && [ ! -f "$CONF.orig" ] && cp -a "$CONF" "$CONF.orig"
cat > "$CONF" <<EOF
# generated by 密聊 ops/install-coturn.sh
listening-port=3478
$( [ -n "$CERT" ] && echo "tls-listening-port=5349" )
listening-ip=$PRIVATE_IP
relay-ip=$PRIVATE_IP
external-ip=$EXTERNAL
min-port=$MIN_PORT
max-port=$MAX_PORT
realm=$DOMAIN
server-name=$DOMAIN
use-auth-secret
static-auth-secret=$SECRET
fingerprint
$( [ -n "$CERT" ] && printf 'cert=%s\npkey=%s\n' "$TLS_DIR/fullchain.pem" "$TLS_DIR/privkey.pem" )
no-tlsv1
no-tlsv1_1
no-cli
no-multicast-peers
no-rfc5780
no-stun-backward-compatibility
response-origin-only-with-rfc5780
stale-nonce=600
user-quota=12
total-quota=200
max-bps=3000000
# never relay into private / special networks (SSRF protection)
denied-peer-ip=0.0.0.0-0.255.255.255
denied-peer-ip=10.0.0.0-10.255.255.255
denied-peer-ip=100.64.0.0-100.127.255.255
denied-peer-ip=127.0.0.0-127.255.255.255
denied-peer-ip=169.254.0.0-169.254.255.255
denied-peer-ip=172.16.0.0-172.31.255.255
denied-peer-ip=192.0.0.0-192.0.0.255
denied-peer-ip=192.0.2.0-192.0.2.255
denied-peer-ip=192.88.99.0-192.88.99.255
denied-peer-ip=192.168.0.0-192.168.255.255
denied-peer-ip=198.18.0.0-198.19.255.255
denied-peer-ip=198.51.100.0-198.51.100.255
denied-peer-ip=203.0.113.0-203.0.113.255
denied-peer-ip=224.0.0.0-255.255.255.255
denied-peer-ip=::1
denied-peer-ip=64:ff9b::-64:ff9b::ffff:ffff
denied-peer-ip=::ffff:0.0.0.0-::ffff:255.255.255.255
denied-peer-ip=100::-100::ffff:ffff:ffff:ffff
denied-peer-ip=2001::-2001:1ff:ffff:ffff:ffff:ffff:ffff:ffff
denied-peer-ip=2002::-2002:ffff:ffff:ffff:ffff:ffff:ffff:ffff
denied-peer-ip=fc00::-fdff:ffff:ffff:ffff:ffff:ffff:ffff:ffff
denied-peer-ip=fe80::-febf:ffff:ffff:ffff:ffff:ffff:ffff:ffff
log-file=syslog
simple-log
EOF
chmod 640 "$CONF"
chgrp "$(id -gn "$TURN_USER")" "$CONF" 2>/dev/null || true
[ -f /etc/default/coturn ] && sed -i 's/^#\?TURNSERVER_ENABLED=.*/TURNSERVER_ENABLED=1/' /etc/default/coturn

# refresh the cert copy daily (Let's Encrypt renews every ~60 days)
if [ -n "$CERT" ]; then
  cat > /etc/systemd/system/coturn-cert-sync.service <<EOF
[Unit]
Description=Copy the site certificate for coturn
[Service]
Type=oneshot
ExecStart=/bin/sh -c 'cmp -s "$CERT" "$TLS_DIR/fullchain.pem" || { install -m 640 -o root -g $(id -gn "$TURN_USER") "$CERT" "$TLS_DIR/fullchain.pem"; install -m 640 -o root -g $(id -gn "$TURN_USER") "$KEY" "$TLS_DIR/privkey.pem"; systemctl restart coturn; }'
EOF
  cat > /etc/systemd/system/coturn-cert-sync.timer <<'EOF'
[Unit]
Description=Daily coturn certificate sync
[Timer]
OnCalendar=*-*-* 04:47
Persistent=true
[Install]
WantedBy=timers.target
EOF
  systemctl daemon-reload
  systemctl enable --now coturn-cert-sync.timer >/dev/null
fi

systemctl enable coturn >/dev/null 2>&1 || true
systemctl restart coturn
sleep 1
systemctl is-active --quiet coturn || { journalctl -u coturn -n 30 --no-pager; echo "coturn 启动失败"; exit 1; }

# ---------------------------------------------------------------- 5) tell the app
URLS="stun:$DOMAIN:3478,turn:$DOMAIN:3478?transport=udp,turn:$DOMAIN:3478?transport=tcp"
[ -n "$CERT" ] && URLS="$URLS,turns:$DOMAIN:5349?transport=tcp"
ENV="$APP_DIR/.env"
# written as the app user: .env lives in the web user's folder
as_app sh -c 'umask 077; touch "$1" && sed -i "/^TURN_URLS=/d; /^TURN_SECRET=/d" "$1" && printf "TURN_URLS=%s\nTURN_SECRET=%s\n" "$2" "$3" >> "$1" && chmod 600 "$1"' _ "$ENV" "$URLS" "$SECRET"
backup_env || true
systemctl restart "$SERVICE"
wait_healthy 30 || { echo "应用重启后没有响应，请运行 ops/status.sh 查看"; exit 1; }

log "✔ coturn 已启用：$URLS"
echo
echo "还差一步：在【阿里云安全组】和【宝塔 → 安全】里放行："
echo "    3478/udp  3478/tcp  $( [ -n "$CERT" ] && echo '5349/tcp  ')${MIN_PORT}-${MAX_PORT}/udp"
echo "放行后，在两台不同网络的设备上互相拨打一次测试。"
